def profile_text(user):
    import time
    now_ms = int(time.time() * 1000)
    if user["expiry_ms"] > now_ms:
        days_left = (user["expiry_ms"] - now_ms) // (24 * 60 * 60 * 1000)
        status = f"✅ Активна, осталось {days_left} дн."
    else:
        status = "❌ Не активна"
    return f"👤 Ваш профиль\n\nПодписка: {status}"


