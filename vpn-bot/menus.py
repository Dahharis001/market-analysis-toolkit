_MD_SPECIAL_RE = re.compile(r"([_*\[\]()~`>#+\-=|{}.!])")


def _escape_md(text):
    return _MD_SPECIAL_RE.sub(r"\\\1", text)


def _code(text):
    escaped = text.replace("\\", "\\\\").replace("`", "\\`")
    return "`" + escaped + "`"

